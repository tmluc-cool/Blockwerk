// Checks the licenses of all dependencies and generates THIRD_PARTY.md.
//
//   node scripts/licenses.mjs          check and rewrite THIRD_PARTY.md
//   node scripts/licenses.mjs --check  check and fail if THIRD_PARTY.md is outdated (CI, pnpm lint)
//
// Allowed: MIT, Apache-2.0, BSD, ISC, Zlib, CC0 (CLAUDE.md), including their
// public-domain-like variants MIT-0 and 0BSD.

import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'THIRD_PARTY.md');
const checkOnly = process.argv.includes('--check');

const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'ISC',
  'Zlib',
  'CC0-1.0',
]);

/**
 * Transitive production packages under other permissive licenses that are not part of any
 * shipped bundle. Each entry needs a reason.
 */
const NOT_SHIPPED = {
  'lru-cache':
    'BlueOak-1.0.0; dependency of jsdom, which Blockly only uses under Node.js. Not in the editor bundle.',
};

/** Whether an SPDX expression allows use under one of the allowed licenses. */
function isAllowed(expression) {
  return expression
    .replace(/[()]/g, ' ')
    .split(/\s+OR\s+/i)
    .some((alternative) =>
      alternative.split(/\s+AND\s+/i).every((part) => ALLOWED.has(part.trim())),
    );
}

function licenseOf(manifest) {
  const license = manifest.license ?? manifest.licenses;
  if (typeof license === 'string') return license;
  if (Array.isArray(license)) return license.map((item) => item.type ?? item).join(' OR ');
  if (license && typeof license === 'object') return license.type ?? 'UNKNOWN';
  return 'UNKNOWN';
}

function workspaceDirs() {
  const dirs = [root];
  for (const group of ['packages', 'apps']) {
    for (const name of readdirSync(join(root, group))) {
      if (existsSync(join(root, group, name, 'package.json'))) dirs.push(join(root, group, name));
    }
  }
  return dirs;
}

const problems = [];

// 1. Direct dependencies of every workspace package.
const direct = new Map();
for (const dir of workspaceDirs()) {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const workspace = relative(root, dir).split(sep).join('/') || '(root)';
  for (const [kind, deps] of [
    ['runtime', manifest.dependencies ?? {}],
    ['development', manifest.devDependencies ?? {}],
  ]) {
    for (const [name, range] of Object.entries(deps)) {
      if (String(range).startsWith('workspace:')) continue;
      const manifestPath = join(dir, 'node_modules', name, 'package.json');
      if (!existsSync(manifestPath)) {
        problems.push(`${name} (${workspace}) is not installed; run pnpm install.`);
        continue;
      }
      const installed = JSON.parse(readFileSync(manifestPath, 'utf8'));
      const entry = direct.get(name) ?? {
        name,
        version: installed.version,
        license: licenseOf(installed),
        usedBy: new Set(),
        kinds: new Set(),
      };
      entry.usedBy.add(workspace);
      entry.kinds.add(kind);
      direct.set(name, entry);
    }
  }
}
for (const entry of direct.values()) {
  if (!isAllowed(entry.license))
    problems.push(`${entry.name}@${entry.version}: license "${entry.license}" is not allowed.`);
}

// 2. Everything installed as a production dependency (what can end up in the editor or app).
const report = JSON.parse(
  execSync('pnpm licenses list --json --prod', { cwd: root, encoding: 'utf8' }),
);
const production = [];
for (const [license, packages] of Object.entries(report)) {
  for (const pkg of packages) {
    production.push({ name: pkg.name, versions: [...pkg.versions].sort().join(', '), license });
    if (!isAllowed(license) && !NOT_SHIPPED[pkg.name]) {
      problems.push(`${pkg.name} (production, transitive): license "${license}" is not allowed.`);
    }
  }
}
production.sort((a, b) => a.name.localeCompare(b.name));

// 3. THIRD_PARTY.md
const directRows = [...direct.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(
    (entry) =>
      `| \`${entry.name}\` | ${entry.version} | ${entry.license} | ${[...entry.kinds].sort().join(', ')} | ${[...entry.usedBy].sort().join(', ')} |`,
  );
const productionRows = production.map(
  (pkg) => `| \`${pkg.name}\` | ${pkg.versions} | ${pkg.license} |`,
);
const exceptionRows = Object.entries(NOT_SHIPPED).map(
  ([name, reason]) => `| \`${name}\` | ${reason} |`,
);

const content = `# Third-party software

Generated by \`pnpm run licenses\` (\`scripts/licenses.mjs\`). Do not edit by hand; \`pnpm lint\` fails if this file is outdated.

Blockwerk itself is licensed under the MIT License (see \`LICENSE\`). Dependencies must use one of these licenses: MIT, Apache-2.0, BSD (2- or 3-clause), ISC, Zlib or CC0, including the public-domain-like variants MIT-0 and 0BSD.

## Direct dependencies

| Package | Version | License | Kind | Used by |
|---|---|---|---|---|
${directRows.join('\n')}

## Production dependencies including transitive ones

Everything that is installed for running the editor, the runtime or the desktop app. Build and test tools are not listed here.

| Package | Versions | License |
|---|---|---|
${productionRows.join('\n')}

## Exceptions

Packages under other permissive licenses that are installed as transitive production dependencies but are not part of any shipped bundle:

| Package | Reason |
|---|---|
${exceptionRows.join('\n')}

## Assets

The asset library start pack (from phase 2) contains only CC0 assets. Its sources and licenses are listed in \`library/LICENSES.md\`, generated by \`pnpm assets:fetch\`.
`;

if (problems.length > 0) {
  console.error('License problems:\n' + problems.map((problem) => `  - ${problem}`).join('\n'));
  process.exit(1);
}

const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
if (checkOnly) {
  if (current !== content) {
    const expectedLines = content.split('\n');
    const actualLines = current.split('\n');
    const line = expectedLines.findIndex((text, index) => text !== actualLines[index]);
    console.error('THIRD_PARTY.md is outdated. Run `pnpm run licenses` and commit the result.');
    console.error(`First difference in line ${line + 1}:`);
    console.error(`  expected: ${expectedLines[line] ?? '(end of file)'}`);
    console.error(`  found:    ${actualLines[line] ?? '(end of file)'}`);
    process.exit(1);
  }
  console.log(`Licenses OK (${direct.size} direct, ${production.length} production packages).`);
} else {
  writeFileSync(outputPath, content);
  console.log(
    `THIRD_PARTY.md written (${direct.size} direct, ${production.length} production packages).`,
  );
}
