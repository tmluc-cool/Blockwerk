import type { GameObject } from './GameObject';

/** Services available to compiled block scripts as `game`. Grows with each phase. */
export interface GameServices {
  /** Number of logic ticks since the game started. */
  readonly tick: number;
}

/** A compiled block script thread. Each `yield` hands control back until the next logic tick. */
export type ScriptThread = (self: GameObject, game: GameServices) => Generator<void, void, void>;

/** The event that starts a script (the hat block). */
export interface ScriptEvent {
  /** Event name, e.g. `start` (Unity: Start) or `update` (Unity: Update). */
  type: string;
  /** Event parameters, e.g. the key of a key event. */
  params?: Readonly<Record<string, string | number | boolean>>;
}

/** One script of a compiled block-script asset. */
export interface ScriptEntry {
  /** Stable ID of the hat block the script starts with. */
  id: string;
  event: ScriptEvent;
  run: ScriptThread;
}

/** The result of evaluating the JavaScript generated by the compiler for one block-script asset. */
export interface CompiledScriptModule {
  scripts: ScriptEntry[];
}

/** Error raised when generated code does not have the expected module shape. */
export class ScriptModuleError extends Error {
  override readonly name = 'ScriptModuleError';
}

function isScriptEntry(value: unknown): value is ScriptEntry {
  if (typeof value !== 'object' || value === null) return false;
  const entry = value as Record<string, unknown>;
  const event = entry['event'] as Record<string, unknown> | undefined;
  return (
    typeof entry['id'] === 'string' &&
    typeof entry['run'] === 'function' &&
    typeof event === 'object' &&
    event !== null &&
    typeof event['type'] === 'string'
  );
}

/**
 * Evaluates compiler output (a function body that returns `{ scripts }`) and returns
 * the script entries. The code runs without access to the enclosing scope.
 */
export function loadScriptModule(code: string): CompiledScriptModule {
  const factory = new Function(code) as () => unknown;
  const result = factory();
  if (typeof result !== 'object' || result === null) {
    throw new ScriptModuleError('Generated code did not return a module object.');
  }
  const scripts = (result as Record<string, unknown>)['scripts'];
  if (!Array.isArray(scripts) || !scripts.every(isScriptEntry)) {
    throw new ScriptModuleError('Generated code returned an invalid script list.');
  }
  return { scripts };
}
