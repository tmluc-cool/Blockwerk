import type { BlockRegistry, CompileArgs, BlockInputs } from '@blockwerk/blocks';
import type { IRExpression, IRFunction, IRProgram, IRScript, IRStatement } from './ir';
import { identifier, NameTable } from './names';

/** Generated JavaScript plus the mapping from output lines to block IDs. */
export interface GeneratedCode {
  /** Function body that returns `{ scripts }` (see `loadScriptModule` in the runtime). */
  readonly code: string;
  /** For every line of `code` (0-based) the ID of the block it came from, or `null`. */
  readonly lineToBlock: readonly (string | null)[];
}

/** Options for {@link generateCode}. */
export interface CodegenOptions {
  /** Name of the block-script asset, written into the header comment. */
  readonly assetName: string;
}

const INDENT = '  ';
const SUBSTACK_MARKER = (name: string): string => `/*@substack:${name}*/`;
const SIMPLE_EXPRESSION =
  /^(?:-?\d+(?:\.\d+)?(?:e[+-]?\d+)?|"(?:[^"\\]|\\.)*"|[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*(?:\([^()]*\))?)$/;

/** Thrown when IR references something that does not exist. */
export class CodegenError extends Error {
  override readonly name = 'CodegenError';
}

class Writer {
  readonly lines: string[] = [];
  readonly lineToBlock: (string | null)[] = [];

  line(depth: number, text: string, blockId: string | null): void {
    this.lines.push(text === '' ? '' : INDENT.repeat(depth) + text);
    this.lineToBlock.push(blockId);
  }
}

class Generator {
  private readonly names = new NameTable();
  private readonly writer = new Writer();

  constructor(
    private readonly registry: BlockRegistry,
    private readonly program: IRProgram,
  ) {}

  generate(options: CodegenOptions): GeneratedCode {
    const w = this.writer;
    w.line(0, '// Generated by Blockwerk. Do not edit.', null);
    w.line(0, `// asset: ${options.assetName.replace(/[\r\n]/g, ' ')}`, null);
    for (const fn of this.program.functions) this.function(fn);
    for (const script of this.program.scripts) this.script(script);
    w.line(0, 'return {', null);
    w.line(1, 'scripts: [', null);
    for (const script of this.program.scripts) {
      const event = JSON.stringify(script.event);
      w.line(
        2,
        `{ id: ${JSON.stringify(script.id)}, event: ${event}, run: ${this.scriptName(script)} },`,
        script.id,
      );
    }
    w.line(1, '],', null);
    w.line(0, '};', null);
    return { code: w.lines.join('\n') + '\n', lineToBlock: [...w.lineToBlock, null] };
  }

  private scriptName(script: IRScript): string {
    return this.names.get('s_', script.id);
  }

  private functionName(functionId: string): string {
    return this.names.get('f_', functionId);
  }

  private script(script: IRScript): void {
    this.writer.line(0, '', null);
    this.writer.line(0, `function* ${this.scriptName(script)}(self, game) {`, script.id);
    this.statements(script.body, 1);
    this.writer.line(0, '}', script.id);
  }

  private function(fn: IRFunction): void {
    const params = ['self', 'game', ...fn.params.map((param) => identifier('p_', param))];
    this.writer.line(0, '', null);
    this.writer.line(0, `function* ${this.functionName(fn.id)}(${params.join(', ')}) {`, fn.id);
    this.statements(fn.body, 1);
    this.writer.line(0, '}', fn.id);
  }

  private statements(statements: readonly IRStatement[], depth: number): void {
    for (const statement of statements) this.statement(statement, depth);
  }

  private statement(statement: IRStatement, depth: number): void {
    const w = this.writer;
    const blockId = statement.kind === 'block' ? statement.blockId : (statement.blockId ?? null);
    switch (statement.kind) {
      case 'declareLocal':
        w.line(
          depth,
          `let ${identifier('l_', statement.name)} = ${this.expression(statement.value)};`,
          blockId,
        );
        return;
      case 'setLocal':
        w.line(
          depth,
          `${identifier('l_', statement.name)} = ${this.expression(statement.value)};`,
          blockId,
        );
        return;
      case 'return':
        w.line(
          depth,
          statement.value ? `return ${this.expression(statement.value)};` : 'return;',
          blockId,
        );
        return;
      case 'call':
        w.line(depth, `yield* ${this.call(statement.functionId, statement.args)};`, blockId);
        return;
      case 'block':
        this.blockStatement(statement, depth);
        return;
    }
  }

  private blockStatement(statement: Extract<IRStatement, { kind: 'block' }>, depth: number): void {
    const definition = this.registry.get(statement.type);
    if (
      !definition ||
      definition.shape === 'hat' ||
      definition.shape === 'reporter' ||
      definition.shape === 'boolean'
    ) {
      throw new CodegenError(`"${statement.type}" is not a statement block.`);
    }
    const args: Record<string, string> = {};
    for (const [name, input] of Object.entries(definition.inputs)) {
      if (input.type === 'statement') {
        args[name] = SUBSTACK_MARKER(name);
      } else {
        const arg = statement.args[name];
        if (!arg) throw new CodegenError(`"${statement.type}" is missing input "${name}".`);
        args[name] = this.expression(arg);
      }
    }
    const code = definition.compile(args as CompileArgs<BlockInputs>);
    for (const rawLine of code.split('\n')) {
      const leading = rawLine.length - rawLine.trimStart().length;
      const extraDepth = Math.floor(leading / INDENT.length);
      const trimmed = rawLine.trim();
      const substack = Object.keys(statement.substacks).find(
        (name) => trimmed === SUBSTACK_MARKER(name),
      );
      if (substack !== undefined) {
        this.statements(statement.substacks[substack] ?? [], depth + extraDepth);
      } else if (trimmed !== '') {
        this.writer.line(depth + extraDepth, trimmed, statement.blockId);
      }
    }
  }

  private expression(expression: IRExpression): string {
    switch (expression.kind) {
      case 'literal':
        return literal(expression.value);
      case 'local':
        return identifier('l_', expression.name);
      case 'param':
        return identifier('p_', expression.name);
      case 'call':
        return `(yield* ${this.call(expression.functionId, expression.args)})`;
      case 'block': {
        const definition = this.registry.get(expression.type);
        if (!definition || (definition.shape !== 'reporter' && definition.shape !== 'boolean')) {
          throw new CodegenError(`"${expression.type}" is not a value block.`);
        }
        const args: Record<string, string> = {};
        for (const name of Object.keys(definition.inputs)) {
          const arg = expression.args[name];
          if (!arg) throw new CodegenError(`"${expression.type}" is missing input "${name}".`);
          args[name] = this.expression(arg);
        }
        const code = definition.compile(args as CompileArgs<BlockInputs>);
        return SIMPLE_EXPRESSION.test(code) ? code : `(${code})`;
      }
    }
  }

  private call(functionId: string, args: readonly IRExpression[]): string {
    if (!this.program.functions.some((fn) => fn.id === functionId)) {
      throw new CodegenError(`Unknown function "${functionId}".`);
    }
    const values = ['self', 'game', ...args.map((arg) => this.expression(arg))];
    return `${this.functionName(functionId)}(${values.join(', ')})`;
  }
}

/** JavaScript source for a literal value. Non-finite numbers become `0` (as in Scratch). */
export function literal(value: number | string | boolean): string {
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return '0';
    return Object.is(value, -0) ? '0' : String(value);
  }
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

/** Generates JavaScript for an IR program. Pure function: same input, same output. */
export function generateCode(
  program: IRProgram,
  registry: BlockRegistry,
  options: CodegenOptions,
): GeneratedCode {
  return new Generator(registry, program).generate(options);
}
